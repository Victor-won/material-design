import { chromium } from 'playwright-core'
const browser = await chromium.launch({ executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless:true })
const page = await browser.newPage({ viewport:{ width: 900, height: 760 } })
const errors=[]; page.on('pageerror', e=>errors.push(e.message)); page.on('console', m=>{if(m.type()==='error')errors.push(m.text())})
await page.goto('http://127.0.0.1:5173/', { waitUntil:'networkidle' }); await page.waitForTimeout(1000)
console.log('OVERFLOW', await page.evaluate(()=>({s:document.documentElement.scrollWidth,c:document.documentElement.clientWidth})))
await page.getByRole('button',{name:'打开展开图'}).first().click(); await page.waitForTimeout(500)
console.log('NET OPEN', await page.locator('.net-shell').evaluate(el=>getComputedStyle(el).transform))
await page.getByRole('button',{name:'关闭展开图'}).click(); await page.waitForTimeout(400)
await page.getByRole('button',{name:'打开属性面板'}).click(); await page.waitForTimeout(500)
console.log('PROP OPEN', await page.locator('.property-shell').evaluate(el=>getComputedStyle(el).transform))
await page.screenshot({path:'/tmp/mobile-final.png',fullPage:true})
console.log('ERRORS', errors)
await browser.close()
